export const archiveDecades = [...new Set(archive.map((i) => i.decade))].sort(
  (a, b) => a - b
)

export const suppliedItems = archive.filter((i) => i.asset)
export const placeholderItems = archive.filter((i) => !i.asset)

export type ArchiveSection = {
  category: ArchiveCategory
  items: ArchiveItem[]
  decades: number[]
}

/** Category first, decade second. At 140+ items a single chronological list
 *  buries a family snapshot between a newspaper clipping and a cruise photo;
 *  grouping by subject first, then by decade within it, keeps each section
 *  legible while still reading oldest-to-newest within a topic.
 *
 *  Extracted from Archive.astro so the grouping logic — category order,
 *  decade dedup/sort, empty-category exclusion — is unit-testable without a
 *  component-rendering harness this project doesn't otherwise use. */
export function buildArchiveSections(items: ArchiveItem[] = archive): ArchiveSection[] {
  return archiveCategoryOrder
    .map((category) => {
      const categoryItems = items.filter((item) => item.category === category)
      const decades = [...new Set(categoryItems.map((i) => i.decade))].sort((a, b) => a - b)
      return { category, items: categoryItems, decades }
    })
    .filter((s) => s.items.length > 0)
}

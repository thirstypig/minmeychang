#!/usr/bin/env node
// Regenerates tests/data/simplified-only.ts from OpenCC's STCharacters.txt.
//
//   curl -sSfLo /tmp/STCharacters.txt \
//     https://raw.githubusercontent.com/BYVoid/OpenCC/master/data/dictionary/STCharacters.txt
//   curl -sSfLo /tmp/TWVariants.txt \
//     https://raw.githubusercontent.com/BYVoid/OpenCC/master/data/dictionary/TWVariants.txt
//   node scripts/build-simplified-table.mjs /tmp/STCharacters.txt /tmp/TWVariants.txt
//
// Each line of STCharacters is `简<TAB>繁 [繁…]`. A character that is ALSO valid
// Traditional lists itself among its mappings — `台	臺 檯 颱 台`, `后	後 后`,
// `里	裏 里 哩` — so the rule is: keep only entries whose mappings do not include
// the key. That excludes 台, 里, 后, 干, 才, 面, and every character identical
// in both scripts (the 敏 mistake recorded in chinese-copy.test.ts).
//
// OpenCC's Traditional is not Taiwan's: it suggests 爲 for 为 and 衆 for 众,
// and lists 峯 as the Traditional of 峰. Every mapping is first passed through
// TWVariants (爲→為, 衆→眾, 峯→峰), so suggestions are the Taiwan form and a
// character whose Taiwan form is itself (峰) is excluded like 台.
//
// TAIWAN_EXTRA adds what OpenCC deliberately leaves out because the character
// exists in Traditional, but which in this site's copy is only ever a paste:
// 万 (Taiwan writes 萬). Keep this list short and justified.
//
// The file is passed as an argument and only parsed as text; it is not run.

import { readFileSync, writeFileSync } from 'node:fs'

const [input, variantsFile] = process.argv.slice(2)
if (!input || !variantsFile) {
  console.error('usage: node scripts/build-simplified-table.mjs <STCharacters.txt> <TWVariants.txt>')
  process.exit(1)
}

const TAIWAN_EXTRA = [['万', '萬']]

const tw = new Map()
for (const line of readFileSync(variantsFile, 'utf8').split('\n')) {
  const [from, to] = line.split('\t')
  if (from && to) tw.set(from, to.trim().split(/\s+/)[0])
}
if (!(tw.get('爲') === '為' && tw.get('峯') === '峰')) {
  console.error('second argument does not look like TWVariants.txt (爲→為, 峯→峰 missing)')
  process.exit(1)
}

const pairs = []
for (const line of readFileSync(input, 'utf8').split('\n')) {
  const [key, values] = line.split('\t')
  if (!key || !values || [...key].length !== 1) continue
  const options = values.trim().split(/\s+/).map((o) => tw.get(o) ?? o)
  if (options.includes(key)) continue
  pairs.push([key, options[0]])
}
for (const [s, t] of TAIWAN_EXTRA) if (!pairs.some(([k]) => k === s)) pairs.push([s, t])
pairs.sort(([a], [b]) => a.codePointAt(0) - b.codePointAt(0))

if (pairs.length < 2000) {
  console.error(`only ${pairs.length} pairs parsed — is this really STCharacters.txt?`)
  process.exit(1)
}

const body = pairs.map(([s, t]) => s + t).join('')
const out = `// GENERATED by scripts/build-simplified-table.mjs — do not edit by hand.
// Source: OpenCC data/dictionary/STCharacters.txt (Apache-2.0),
// https://github.com/BYVoid/OpenCC. Generated ${new Date().toISOString().slice(0, 10)}.
//
// with OpenCC TWVariants.txt applied, plus TAIWAN_EXTRA (万).
//
// ${pairs.length} simplified-only characters, each followed by its Taiwan
// Traditional form, as one string of pairs. Characters that are also valid
// Taiwan Traditional (台, 里, 后, 干, 才, 峰…) are excluded by the generator's
// rule; see the generator's header for it.

const CHARS = [...'${body}']

export const simplifiedToTraditional: ReadonlyMap<string, string> = new Map(
  Array.from({ length: CHARS.length / 2 }, (_, i) => [CHARS[2 * i], CHARS[2 * i + 1]] as [string, string]),
)
`
writeFileSync('tests/data/simplified-only.ts', out)
console.log(`wrote tests/data/simplified-only.ts — ${pairs.length} pairs`)
